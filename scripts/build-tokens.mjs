// Generates src/styles/tokens.css from design/tokens.json.
// tokens.json is the source of truth: edit it, not the generated CSS.
// Dark is the default theme whatever the OS prefers. Light applies only when
// <html data-theme="light"> is set by the footer toggle (remembered on the device).

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const tokens = JSON.parse(await readFile(new URL('design/tokens.json', root), 'utf8'));

// Fontsource variable packages register these family names.
const FONT_FAMILIES = {
  sans: '"Rethink Sans Variable", "Rethink Sans", system-ui, sans-serif',
  mono: '"JetBrains Mono Variable", "JetBrains Mono", ui-monospace, monospace',
};

// Fluid sizes for the display styles, as given in each style's usage note.
const FLUID = {
  poster: 'clamp(3.25rem, 18cqi, 15rem)',
  statement: 'clamp(2.75rem, 7cqi, 4.5rem)',
};

const colors = (theme) =>
  tokens.color.tokens.map((t) => `  --color-${t.name}: ${t.value[theme]};`).join('\n');

const unitless = (v) => (typeof v === 'number' ? String(v) : v);

const typeLines = [];
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    const p = `--type-${s.name}`;
    typeLines.push(`  ${p}-family: var(--font-${group.family});`);
    typeLines.push(`  ${p}-size: ${FLUID[s.name] ?? s.fontSize};`);
    typeLines.push(`  ${p}-line-height: ${unitless(s.lineHeight)};`);
    typeLines.push(`  ${p}-letter-spacing: ${s.letterSpacing ?? 'normal'};`);
    typeLines.push(`  ${p}-weight: ${s.fontWeight};`);
  }
}

const simple = (section, prefix) =>
  tokens[section].tokens.map((t) => `  --${prefix}${t.name}: ${t.value};`).join('\n');

const css = `/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit. */

:root {
  color-scheme: dark;
${colors('dark')}

  --font-sans: ${FONT_FAMILIES.sans};
  --font-mono: ${FONT_FAMILIES.mono};

${typeLines.join('\n')}

${simple('spacing', '')}

${simple('radius', '')}

${simple('borderWidth', 'border-')}
}

:root[data-theme='light'] {
  color-scheme: light;
${colors('light')}
}
`;

const out = new URL('src/styles/tokens.css', root);
await mkdir(new URL('.', out), { recursive: true });
await writeFile(out, css);
console.log(`tokens: wrote ${fileURLToPath(out)}`);
